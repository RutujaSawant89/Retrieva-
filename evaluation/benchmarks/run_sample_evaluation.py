"""Run the Northwind sample evaluation end-to-end through a running Retrieva API.

Uploads the sample corpus, uploads the labelled dataset, runs the retrieval-strategy experiment
(BM25 vs dense vs hybrid vs hybrid + rerank), waits for completion and writes
``evaluation/reports/northwind_strategies.{json,md}`` from the stored run metrics.

Usage::

    RETRIEVA_EMAIL=you@example.com RETRIEVA_PASSWORD=... \\
        uv run python ../evaluation/benchmarks/run_sample_evaluation.py --api http://localhost:8000
"""

from __future__ import annotations

import argparse
import json
import os
import time
from datetime import UTC, datetime
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "evaluation" / "datasets" / "sample_corpus"
DATASET = ROOT / "evaluation" / "datasets" / "northwind-qa.json"
REPORTS = ROOT / "evaluation" / "reports"
METRICS = [
    "precision@1",
    "recall@5",
    "mrr",
    "ndcg@10",
    "context_precision",
    "faithfulness",
    "citation_precision",
    "retrieval_ms",
]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--api", default="http://localhost:8000")
    parser.add_argument("--generate", action="store_true", help="also generate and verify answers")
    args = parser.parse_args()

    client = httpx.Client(base_url=f"{args.api}/api/v1", timeout=600)
    session = client.post(
        "/auth/login",
        json={"email": os.environ["RETRIEVA_EMAIL"], "password": os.environ["RETRIEVA_PASSWORD"]},
    )
    session.raise_for_status()
    headers = {"Authorization": f"Bearer {session.json()['access_token']}"}

    files = [("files", (p.name, p.read_bytes(), "text/markdown")) for p in sorted(CORPUS.glob("*.md"))]
    upload = client.post(
        "/documents/upload", headers=headers, files=files, data={"category": "Northwind sample"}
    )
    upload.raise_for_status()
    # Already-uploaded files come back as duplicates pointing at the existing document.
    ids = [r["document"]["id"] if r["document"] else r["duplicate_of"] for r in upload.json()["results"]]
    ids = [i for i in ids if i]
    for doc_id in ids:
        while client.get(f"/documents/{doc_id}/status", headers=headers).json()["status"] not in (
            "completed",
            "failed",
        ):
            time.sleep(1)
    print(f"Corpus ready ({len(ids)} documents)")

    dataset_payload = json.loads(DATASET.read_text(encoding="utf-8"))
    dataset = client.post(
        "/evaluation/datasets",
        headers=headers,
        json={
            "name": "Northwind Q&A",
            "description": dataset_payload["description"],
            "items": dataset_payload["items"],
        },
    ).json()
    runs = client.post(
        "/evaluation/run",
        headers=headers,
        json={
            "dataset_id": dataset["id"],
            "name": "Retrieval strategies",
            "preset": "retrieval_strategies",
            "generate": args.generate,
            "document_ids": ids,  # evaluate on the sample corpus only
        },
    ).json()
    pending = {r["id"] for r in runs}
    results = {}
    while pending:
        for run_id in list(pending):
            detail = client.get(f"/evaluation/runs/{run_id}", headers=headers).json()
            if detail["status"] in ("completed", "failed"):
                pending.discard(run_id)
                results[run_id] = detail
                print(detail["name"], detail["status"], detail.get("error_message") or "")
        time.sleep(2)

    ordered = [results[r["id"]] for r in runs]
    report = {
        "dataset": f"Northwind Q&A v{dataset['version']} ({dataset['item_count']} questions)",
        "date": datetime.now(UTC).isoformat(timespec="seconds"),
        "embedding_model": ordered[0]["embedding_model"],
        "reranker": next((r["reranker_model"] for r in ordered if r["reranker_model"]), None),
        "llm": ordered[0]["llm_model"],
        "runs": [
            {"name": r["config"]["experiment"], "config": r["config"]["retrieval"], "metrics": r["metrics"]}
            for r in ordered
        ],
    }
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "northwind_strategies.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    present = [m for m in METRICS if any(isinstance(r["metrics"].get(m), int | float) for r in ordered)]
    lines = [
        "# Northwind sample — retrieval strategy comparison",
        "",
        f"Measured {report['date']} through the Retrieva API on the fictional Northwind corpus "
        f"(`evaluation/datasets/sample_corpus`, 3 documents) with {report['dataset']}.",
        f"Embeddings `{report['embedding_model']}`; reranker `{report['reranker']}`."
        + (f" Answers generated by `{report['llm']}`." if report["llm"] else ""),
        "",
        "| Configuration | " + " | ".join(present) + " |",
        "| --- | " + " | ".join("---:" for _ in present) + " |",
    ]
    for run in report["runs"]:
        cells = []
        for m in present:
            v = run["metrics"].get(m)
            cells.append("—" if v is None else (f"{v:.0f} ms" if m.endswith("_ms") else f"{v:.3f}"))
        lines.append(f"| {run['name']} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "This corpus is deliberately small (a few dozen chunks), so differences between strategies are",
        "smaller and noisier than on a realistic collection; see `beir_scifact.md` for a larger benchmark.",
    ]
    (REPORTS / "northwind_strategies.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote evaluation/reports/northwind_strategies.{json,md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
